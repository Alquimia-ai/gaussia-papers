"""Standalone entrypoint for GenericRiskEngine (generic risk plugins, no KB).

Deliberately SEPARATE from universal_probe_library.py: GenericRiskEngine.can_handle()
is always True, so if it were registered in build_engines()/--engine compose it would
mix into the canonical Ley 24.977 dataset (dataset_ley_compose.json) without anyone
asking for it. Here it runs alone, with its own result.

ALL probes are generated by the LLM at runtime (see engines_generic.py) from just the
name+description of each plugin — no text is hand-written. With --context you describe
the agent under test so the probes stay anchored to that specific agent; without
--context, they come out domain-agnostic.

Usage:
  python generic_probe_library.py --model "google/gemma-4-31B-it"
  python generic_probe_library.py --model "google/gemma-4-31B-it" --n-per-plugin 5 \
     --context "Online bank tech support assistant: cards, transfers, blocks."
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import probe_library as pl
from engines_generic import GenericRiskEngine

HERE = Path(__file__).resolve().parent.parent  # project root (this file lives in src/)
RESULTS = HERE / "results" / "level1_probes_generic"


def main() -> None:
    ap = argparse.ArgumentParser(description="Generic Risk Probe Library (Roast Me)")
    ap.add_argument("--provider", default="hf_router", help="groq | openai | hf | hf_router")
    ap.add_argument("--model", default=None, help="provider default if not specified")
    ap.add_argument("--n-per-plugin", type=int, default=4,
                    help="how many probes to generate per active plugin")
    ap.add_argument("--context", default=None,
                    help="description of the agent under test (e.g. 'online bank tech "
                         "support assistant'); without this, generates domain-agnostic probes")
    args = ap.parse_args()

    from config import build_client, resolve_model
    client = build_client(args.provider)
    model = resolve_model(args.provider, args.model)

    engine = GenericRiskEngine(client, provider=args.provider, model=model)
    probes = engine.generate_proposed(args.n_per_plugin, context=args.context)

    by_plugin = Counter(p.plugin for p in probes)
    print("\n=== Generic Risk Probe Library ===")
    print(f"model: {model}" + (f"  context={args.context!r}" if args.context else "  (no context, domain-agnostic)"))
    print(f"probes generated: {len(probes)}")
    for plugin_id, n in sorted(by_plugin.items()):
        print(f"  {plugin_id:<26}{n:>3}")

    RESULTS.mkdir(parents=True, exist_ok=True)
    ds_path = RESULTS / "dataset_generic.json"
    sm_path = RESULTS / "summary_generic.json"
    ds_path.write_text(json.dumps(pl.to_records(probes), ensure_ascii=False, indent=2),
                       encoding="utf-8")
    sm_path.write_text(json.dumps(
        {"provider": args.provider, "model": model, "context": args.context,
         "n_per_plugin": args.n_per_plugin, "n_probes": len(probes),
         "by_plugin": dict(by_plugin)},
        ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nwritten: {ds_path.name}, {sm_path.name}")


if __name__ == "__main__":
    main()
